"""File > Export > Send to Notebook: hand a GUI session over to Python.

Writes a folder with everything in the current window (labels, ROIs,
traces, results) plus ``load_session.py``, a snippet that needs only numpy,
tifffile and json. The source image is referenced by path, not copied,
when it came from a file; in-memory images are saved if they are small.
"""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

import numpy as np
from napari.layers import Image, Labels

from . import roi as roi_mod
from . import rois as R

MAX_COPY_BYTES = 2 * 2**30  # in-memory images larger than this are not written


def _safe(name: str) -> str:
    return re.sub(r'[^A-Za-z0-9_.-]+', '_', name).strip('_') or 'layer'


def _loader_line(var: str, path: str) -> str:
    if path.lower().endswith('.npy'):
        return f"{var} = np.load(r'{path}', mmap_mode='r')"
    if path.lower().endswith(('.tif', '.tiff')):
        return f"{var} = tifffile.imread(r'{path}')  # or tifffile.memmap(...) for uncompressed files"
    return f"{var} = skimage.io.imread(r'{path}')"


def export_session(folder, viewer, image, manager_rois=(), traces=(), results_rows=(), results_columns=()) -> tuple[Path, str]:
    """Write the session to ``folder``; returns ``(folder, loader snippet)``."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    manifest: dict = {'image': image.name, 'scale': [float(s) for s in image.scale], 'layers': {}, 'notes': []}
    lines = [
        '# Generated by TIKI "Send to Notebook"',
        'import json',
        'from pathlib import Path',
        '',
        'import numpy as np',
        'import tifffile',
        '',
        f"session = Path(r'{folder}')",
    ]

    # -- image ---------------------------------------------------------
    src = image.metadata.get('path')
    if src and Path(src).exists():
        manifest['image_path'] = src
        lines.append(_loader_line('image', src))
    elif image.data.nbytes <= MAX_COPY_BYTES:
        np.save(folder / 'image.npy', np.asarray(image.data))
        manifest['image_path'] = 'image.npy'
        lines.append("image = np.load(session / 'image.npy', mmap_mode='r')")
    else:
        manifest['notes'].append(f'image ({image.data.nbytes / 2**30:.1f} GB, unsaved) not exported')
        lines.append('image = None  # unsaved image too large to export; save it from TIKI first')

    # -- other layers --------------------------------------------------
    labels_vars = []
    for layer in viewer.layers:
        if layer.name in roi_mod.PREVIEW_NAMES or layer is image:
            continue
        if isinstance(layer, Labels):
            fname = f'labels_{_safe(layer.name)}.npy'
            np.save(folder / fname, np.asarray(layer.data))
            manifest['layers'][layer.name] = {'type': 'labels', 'file': fname}
            labels_vars.append((layer.name, fname))
        elif isinstance(layer, Image) and layer.data.nbytes <= MAX_COPY_BYTES:
            fname = f'image_{_safe(layer.name)}.npy'
            np.save(folder / fname, np.asarray(layer.data))
            manifest['layers'][layer.name] = {'type': 'image', 'file': fname}
    if labels_vars:
        lines.append('labels = {')
        for name, fname in labels_vars:
            lines.append(f"    {name!r}: np.load(session / {fname!r}),")
        lines.append('}')
    other_images = [(n, d['file']) for n, d in manifest['layers'].items() if d['type'] == 'image']
    if other_images:
        lines.append('layers = {')
        for name, fname in other_images:
            lines.append(f"    {name!r}: np.load(session / {fname!r}, mmap_mode='r'),")
        lines.append('}')

    # -- ROIs ------------------------------------------------------------
    rois = list(manager_rois)
    current = roi_mod.current_shape(roi_mod.roi_layer(viewer, create=False))
    if current is not None:
        verts, kind = current
        rois.append(R.Roi('current selection', kind, np.asarray(verts)[:, -2:]))
    if rois:
        R.save_imagej(folder / 'RoiSet.zip', rois)
        shape2d = roi_mod.spatial_shape(image)
        np.save(folder / 'roi_masks.npy', np.stack([r.mask(shape2d) for r in rois]))
        with open(folder / 'rois.json', 'w') as f:
            json.dump([{'name': r.name, 'kind': r.kind, 'yx': r.yx.tolist(),
                        'position': list(r.position) if r.position else None} for r in rois], f, indent=1)
        lines += [
            "rois = json.loads((session / 'rois.json').read_text())   # name, kind, yx vertices",
            "roi_masks = np.load(session / 'roi_masks.npy')           # (n_rois, y, x) bool",
            "# ImageJ/Fiji can open session / 'RoiSet.zip' directly",
        ]

    # -- traces ----------------------------------------------------------
    for i, (title, names, data) in enumerate(traces):
        stem = 'traces' if i == 0 else f'traces_{i + 1}'
        np.save(folder / f'{stem}.npy', np.asarray(data))
        (folder / f'{stem}_names.txt').write_text('\n'.join(names) + '\n')
        manifest.setdefault('traces', []).append({'title': title, 'file': f'{stem}.npy'})
        lines += [
            f"{stem} = np.load(session / '{stem}.npy')   # {title}: cells x frames",
            f"{stem}_names = (session / '{stem}_names.txt').read_text().split('\\n')[:-1]",
        ]

    # -- results ---------------------------------------------------------
    if results_rows:
        with open(folder / 'results.csv', 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=list(results_columns))
            writer.writeheader()
            writer.writerows(results_rows)
        lines.append("results = np.genfromtxt(session / 'results.csv', delimiter=',', names=True, dtype=None, encoding=None)"
                     "  # or pandas.read_csv")

    (folder / 'session.json').write_text(json.dumps(manifest, indent=1))
    snippet = '\n'.join(lines) + '\n'
    (folder / 'load_session.py').write_text(snippet)
    return folder, snippet
